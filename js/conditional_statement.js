// conditional statement (if , else if , else)

let score = 60;

if(score >= 90){
    console.log('You are selected for A Grade University')
}else if(score >=80){
    console.log('You are selected for B Grade University')
}else if(score >=70){
    console.log('You are selected for C Grade University')
}else{
    console.log('You are not selected for any University')
}